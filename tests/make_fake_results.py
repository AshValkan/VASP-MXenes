"""
make_fake_results.py -- fabricates a *finished* results tree so the analysis
pipeline can be exercised before any real VASP run.

This is a development/test tool, not part of the science.  It writes, for
every composition x pattern:

    <root>/<label>/ABC/HM/opt/POSCAR     real, generated by alloy.py
    <root>/<label>/ABC/HM/opt/OUTCAR     fake, parseable by VASPread
    <root>/<label>/ABC/HM/DOS/DOSCAR     fake, with a KNOWN eps_d(y) trend

plus the two end-member references (y = 0 and y = 3) and the experimental
files ``measured.json`` / ``adsorption.json`` that analyze_alloy.py expects.

The fabricated numbers follow a deliberate story so the output figures are
interpretable:

    eps_d(Ti)  moves toward E_F as y increases   (the thesis claim)
    E_ads(H)   becomes more negative as y increases
    C_g        rises with y
    E_mix      convex, minimum near y ~ 1.5      (solid solution favoured)
    E(pattern) outer < sqs < inner < cluster     (V prefers the surface layer)

    python tests/make_fake_results.py                 # writes ./MXenes_alloy
    python tests/make_fake_results.py --root _fake    # somewhere else
"""

from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
os.chdir(ROOT)                      # ./PP must resolve for POTCAR()

from alloy import AlloyMX           # noqa: E402

#: energy model (eV, per supercell)
E_HOST = -600.0                     # Ti3C2O2, y = 0
E_DOPANT = -607.5                   # V3C2O2, y = 3 (hypothetical end member)
MIX_DEPTH = -0.35                   # depth of the convex mixing term
PATTERN_PENALTY = {"outer": 0.00, "sqs": 0.10, "inner": 0.45, "cluster": 0.80,
                   "random": 0.12}


def total_energy(y: float, pattern: str) -> float:
    x = y / 3.0
    linear = (1 - x) * E_HOST + x * E_DOPANT
    ideal = MIX_DEPTH * y * (1 - y / 3.0)
    return linear + ideal + PATTERN_PENALTY.get(pattern, 0.0)


def eps_d_true(y: float, element: str, pattern: str) -> float | None:
    """The d-band centre the synthetic DOSCAR is built around (eV vs E_F)."""
    if element == "Ti":
        if y >= 3.0:
            return None
        return -2.25 + 0.55 * y            # moves toward E_F with V content
    if element == "V":
        if y <= 0.0:
            return None
        shift = -0.05 if pattern == "inner" else 0.0
        return -1.15 + 0.12 * y + shift
    return None


def write_fake_outcar(path: str, energy: float):
    """An OUTCAR stub that VASPread.OUTCAR.getEnergy() can parse."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(" vasp.5.4.4 fake\n")
        for _ in range(3):
            f.write(f"  free  energy   TOTEN    =        {energy:.8f} eV\n")
            f.write("  energy  without entropy=       "
                    f"{energy:.8f}  energy(sigma->0) =        {energy:.8f}\n")


def write_synthetic_doscar(case: str, y: float, pattern: str,
                           mx: AlloyMX, nedos: int = 1501):
    """DOSCAR whose d-band centres are exactly ``eps_d_true``."""
    import numpy as np

    E = np.linspace(-10, 6, nedos)
    EF = 3.0
    Eabs = E + EF
    g = lambda c, w: np.exp(-0.5 * ((E - c) / w) ** 2)

    cTi = eps_d_true(y, "Ti", pattern)
    cV = eps_d_true(y, "V", pattern)
    dTi = g(cTi, 0.55) * 4.0 if cTi is not None else np.zeros_like(E) * 1e-9
    dV = g(cV, 0.55) * 4.0 if cV is not None else np.zeros_like(E) * 1e-9
    pO = g(-5.0, 1.0)

    elements = []
    for el, c in zip(mx.species, mx.counts):
        elements += [el] * c

    os.makedirs(os.path.join(case, "DOS"), exist_ok=True)
    with open(os.path.join(case, "DOS", "DOSCAR"), "w") as f:
        f.write(f" {mx.nAtoms} {mx.nAtoms} 0 0\n 1000.0\n")
        for v in ("6 0 0", "-3 5.19 0", "0 0 27"):
            f.write(" " + v + "\n")
        f.write(" " + mx.label + "\n")
        f.write(f"  6.0 -10.0 {nedos} {EF}\n  energy dos int\n")
        nTi = elements.count("Ti") or 1
        nV = elements.count("V") or 1
        tot = (elements.count("Ti") * dTi + elements.count("V") * dV
               + elements.count("O") * pO)
        for i in range(nedos):
            f.write(f"{Eabs[i]:11.5f}{tot[i]:13.5f}{tot[i] * 0.01:13.5f}\n")
        f.write("\n")
        for el in elements:
            if el == "Ti":
                d, s, p = dTi, 0.1 * dTi, 0.2 * dTi
            elif el == "V":
                d, s, p = dV, 0.1 * dV, 0.2 * dV
            elif el == "O":
                d, s, p = 0.01 * dV, 0.2 * pO, pO
            else:
                d, s, p = 0.02 * dV, 0.3 * pO, 0.5 * pO
            for i in range(nedos):
                f.write(f"{Eabs[i]:11.5f}{s[i]:13.5f}"
                        + "".join(f"{p[i] / 3:13.5f}" for _ in range(3))
                        + "".join(f"{d[i] / 5:13.5f}" for _ in range(5)) + "\n")
            f.write("\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="MXenes_alloy")
    ap.add_argument("--ys", nargs="+", type=float,
                    default=[0.0, 0.5, 1.0, 1.5])
    ap.add_argument("--patterns", nargs="+",
                    default=["outer", "inner", "sqs"])
    ap.add_argument("--outdir", default="tests")
    a = ap.parse_args()

    made = []
    for y in list(a.ys) + [0.0, 3.0]:          # + the two end members
        for pat in dict.fromkeys(list(a.patterns) + ["outer"]):
            if (y, pat) in made:
                continue
            mx = AlloyMX(y=y, pattern=pat, root=a.root)
            try:
                mx.write_inputs(encut=550, vdw="d3")
            except ValueError as e:
                print(f"  [skip] {mx.mxName} {pat}: {e}")
                continue
            case = os.path.join(a.root, mx.label, "ABC", "HM")
            E = total_energy(y, pat)
            write_fake_outcar(os.path.join(case, "opt", "OUTCAR"), E)
            # Upstream's workflow leaves the optimised CONTCAR at the case
            # root -- reproduce that so PDOS()'s upward search has to work
            # the same way it will on the real tree.
            src = os.path.join(case, "opt", "POSCAR")
            if os.path.exists(src):
                with open(src) as f, \
                        open(os.path.join(case, "CONTCAR"), "w") as g:
                    g.write(f.read())
            write_synthetic_doscar(case, y, pat, mx)
            made.append((y, pat))
            print(f"  {mx.label:<44s} E={E:10.4f}  "
                  f"eps_d(Ti)={eps_d_true(y,'Ti',pat)}  "
                  f"eps_d(V)={eps_d_true(y,'V',pat)}")

    # ---- experimental files analyze_alloy.py expects ----------------------
    meas, ads = {}, {}
    for y in a.ys:
        meas[str(y)] = round(285.0 + 62.0 * y, 1)          # F/g, rising with y
        ads[str(y)] = round(-(1.62 + 0.16 * y), 3)         # eV, more favourable
    for name, data in (("measured.json", meas), ("adsorption.json", ads)):
        p = os.path.join(a.outdir, name)
        with open(p, "w") as f:
            json.dump(data, f, indent=2)
        print(f"  -> {p}")

    print(f"\nEnd members for --host-end / --dopant-end:  "
          f"--host-end {E_HOST}  --dopant-end {E_DOPANT}")
    print(f"\nNext:\n"
          f"  python dband.py --scan {a.root}\n"
          f"  python run_alloy.py --analyze "
          f"--exp {a.outdir}/measured.json --ads {a.outdir}/adsorption.json "
          f"--host-end {E_HOST} --dopant-end {E_DOPANT}")


if __name__ == "__main__":
    main()
